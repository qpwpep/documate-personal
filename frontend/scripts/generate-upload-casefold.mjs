import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const target = fileURLToPath(new URL('../src/attachments/casefold.generated.ts', import.meta.url));
const python = `import json, sys, unicodedata
json.dump({"unicode_version": unicodedata.unidata_version, "folds": {chr(i): chr(i).casefold() for i in range(0x110000) if chr(i).casefold() != chr(i)}}, sys.stdout, ensure_ascii=True)`;
const { unicode_version, folds } = JSON.parse(execFileSync('uv', ['run', '--locked', 'python', '-c', python], { cwd: root, encoding: 'utf8' }));
const exceptions = {};
// Comparing every code point also accounts for Python/Node Unicode version differences.
for (let code = 0; code < 0x110000; code += 1) {
  if (code >= 0xd800 && code <= 0xdfff) continue;
  const character = String.fromCodePoint(code);
  const expected = folds[character] ?? character;
  if (character.toLowerCase() !== expected) exceptions[character] = expected;
}
const output = `// Generated by scripts/generate-upload-casefold.mjs; Python Unicode ${unicode_version}.\n// Apply to individual NFC code points before joining; whole-string lowercasing is contextual.\nexport const uploadCasefoldExceptions: Readonly<Record<string, string>> = ${JSON.stringify(exceptions, null, 2)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('Upload casefold data differs from the supported Python/Node runtimes. Run node scripts/generate-upload-casefold.mjs.');
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, output, 'utf8');
}
